"""`ws sync`: build or repair the workspace from its manifest."""

import os
import re
from pathlib import Path

from ws import pool
from ws.git import GitError, git, ignore
from ws.manifest import Repository

# The hub folder holding the library's private context, read by agents in the library.
LIBRARY_CONTEXT = "docs/library"
# The hub folder holding the study index and a mount of each study's notes.
STUDIES = "docs/studies"
STUDY_INDEX = f"{STUDIES}/index.md"
# The hub's skills, linked into every repository, the hub included, beside its own template skills.
HUB_SKILLS = "skills"
# Where a repository keeps its skills, and the link through which Claude Code reads them.
AGENT_SKILLS = ".agents/skills"
CLAUDE_SKILLS = ".claude/skills"
_GENERATED = (
    "<!-- Generated by `ws sync` from the hub: do not edit, it is rewritten. -->"
)


def _status(path: Path) -> list[str]:
    """How an existing clone differs from a clean checkout of its remote.

    Fetches to see whether the remote moved; never merges or checks anything out.
    """
    flags = []
    changes = git("status", "--porcelain", cwd=path).splitlines()
    if changes:
        flags.append(f"dirty ({len(changes)} uncommitted)")
    try:
        git("rev-parse", "--verify", "--quiet", "@{upstream}", cwd=path)
    except GitError:
        flags.append("no upstream to compare with")
        return flags
    try:
        git("fetch", "--quiet", cwd=path)
    except GitError as error:
        flags.append(f"not checked against its remote: {error}")
        return flags
    behind = int(git("rev-list", "--count", "HEAD..@{upstream}", cwd=path))
    if behind:
        flags.append(f"behind ({behind} commit{'s' if behind > 1 else ''})")
    return flags


def _local_agent_files(hub: str) -> dict[str, str]:
    """The library's local agent files by name, each leading to its private context."""
    context = f"../{hub}/{LIBRARY_CONTEXT}"
    where = (
        f"The library's private context is kept in the hub, in `{context}/`: its guidance, "
        "status, plans and agent docs. Files they name that are not in this repository are "
        "there; edit and commit them in the hub."
    )
    read = f"read `{context}/CLAUDE.md` and the files it imports with `@`"
    return {
        # Claude Code follows an import from outside the project only once the user has
        # allowed it in an interactive session, and never in `claude -p`.
        "CLAUDE.local.md": (
            f"{_GENERATED}\n\n{where} If the import below is not in your context, "
            f"{read} before working here.\n\n@{context}/CLAUDE.md\n"
        ),
        "AGENTS.md": f"{_GENERATED}\n\nBefore working here, {read}. {where}\n",
    }


def _write_local_agent_files(path: Path, hub: str) -> list[str]:
    """Write the library's local agent files, git-ignored, where the library has none of its own.

    Returns what needs attention: a file of the same name that ws did not write is kept.
    """
    notes = []
    for name, text in _local_agent_files(hub).items():
        file = path / name
        if git("ls-files", "--", name, cwd=path).strip():
            continue
        ignore(path, name)
        if not file.exists():
            file.write_text(text, encoding="utf-8")
            continue
        current = file.read_text(encoding="utf-8")
        if not current.startswith(_GENERATED):
            notes.append(f"{name} not written by ws, left as is")
        elif current != text:
            file.write_text(text, encoding="utf-8")
    return notes


def symlink(link: Path, target: Path) -> bool:
    """Point `link` at `target` by a relative path; False if something else is in its place."""
    relative = os.path.relpath(target, link.parent)
    if link.is_symlink():
        if os.readlink(link) == relative:
            return True
        link.unlink()
    elif link.exists():
        return False
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(relative, target_is_directory=True)
    return True


def _mount(hub: Path, study: Path) -> list[str]:
    """Mount the study's notes in the hub's studies folder, out of git.

    Returns what needs attention: a study with no notes, or something else in the way.
    """
    relative = f"{STUDIES}/{study.name}"
    mount = hub / relative
    if mount.exists() and not mount.is_symlink():
        return [f"{relative} is not a mount, left as is"]
    if not (study / "docs").is_dir():
        return ["no docs/ to mount"]
    ignore(hub, relative)
    symlink(mount, study / "docs")
    return []


def _link_skills(hub: Path, repository: Path) -> list[str]:
    """Link each hub skill into the repository's skills, and those to Claude Code, out of git.

    Returns what needs attention: a skill or a Claude Code skills folder of the
    repository's own in the way is kept.
    """
    notes = []
    skills = hub / HUB_SKILLS
    for skill in sorted(skills.iterdir()) if skills.is_dir() else []:
        if not skill.is_dir():
            continue
        relative = f"{AGENT_SKILLS}/{skill.name}"
        if git("ls-files", "--", relative, cwd=repository).strip() or not symlink(
            repository / relative, skill
        ):
            notes.append(f"{relative} is not the hub's skill, left as is")
            continue
        ignore(repository, relative)
    claude = repository / CLAUDE_SKILLS
    if not claude.exists() and not claude.is_symlink():
        ignore(repository, CLAUDE_SKILLS)
        symlink(claude, repository / AGENT_SKILLS)
    elif claude.resolve() != (repository / AGENT_SKILLS).resolve():
        notes.append(f"{CLAUDE_SKILLS} is not a link to {AGENT_SKILLS}, left as is")
    return notes


def _unindexed(hub: Path, studies: list[str]) -> list[str]:
    """The studies without their line in the hub's committed study index (`- **<name>**`)."""
    index = hub / STUDY_INDEX
    text = index.read_text(encoding="utf-8") if index.is_file() else ""
    return [
        name
        for name in studies
        if not re.search(rf"^- \*\*{re.escape(name)}\*\*", text, re.MULTILINE)
    ]


def sync(root: Path, repositories: list[Repository]) -> tuple[list[str], bool]:
    """Clone what is missing under `root`, link each clone to the pool and to the hub's
    skills, mount each study's notes in the hub, and write what the workspace generates
    in the library.

    Returns one report line per repository, or one line if the pool cannot be made;
    and success.
    """
    hub = next(
        repository.name for repository in repositories if repository.role == "hub"
    )
    pool_path = pool.location(root)
    try:
        pool_path.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        return [f"pool {pool_path}: FAILED: {error.strerror}"], False
    studies = [
        repository.name for repository in repositories if repository.role == "study"
    ]
    lines = []
    ok = True
    for repository in repositories:
        path = root / repository.name
        try:
            cloned = not path.exists()
            if cloned:
                try:
                    git("clone", "--quiet", repository.url, str(path), cwd=root)
                except GitError as error:
                    raise GitError(f"could not clone: {error}") from error
            elif not (path / ".git").exists():
                raise GitError("exists but is not a git repository")
            try:
                notes = pool.link(path, pool_path)
            except OSError as error:
                raise GitError(f"could not link resources: {error.strerror}") from error
            if repository.role == "library":
                notes += _write_local_agent_files(path, hub)
            elif repository.role == "study":
                try:
                    notes += _mount(root / hub, path)
                except OSError as error:
                    raise GitError(f"could not mount docs: {error.strerror}") from error
            elif repository.role == "hub":
                notes += [
                    f"{name} missing from {STUDY_INDEX}"
                    for name in _unindexed(path, studies)
                ]
            try:
                notes += _link_skills(root / hub, path)
            except OSError as error:
                raise GitError(f"could not link skills: {error.strerror}") from error
            report = ["cloned"] if cloned else _status(path)
            lines.append(f"{repository.name}: {', '.join([*report, *notes]) or 'ok'}")
        except GitError as error:
            ok = False
            lines.append(f"{repository.name}: FAILED: {error}")
    return lines, ok
